const IPHONE_X_ORDER = [
  'X','XR','XS','XS Max','11','11 Pro','11 Pro Max',
  '12 mini','12','12 Pro','12 Pro Max',
  '13 mini','13','13 Pro','13 Pro Max',
  '14','14 Plus','14 Pro','14 Pro Max',
  '15','15 Plus','15 Pro','15 Pro Max',
  '16','16 Plus','16 Pro','16 Pro Max',
  '17','17 Pro','17 Pro Max'
];
const _mIdx = m => IPHONE_X_ORDER.indexOf(m);

// عطل: p (ثابت) أو tiers (متدرّج). rule: m=موديلات صريحة، r=[من,لـ] مدى، بدون م/ر = افتراضي.
// na = موديلات لا ينطبق عليها العطل.
function faultPts(f, model){
  if(f.na && f.na.includes(model)) return null;
  if(f.tiers){
    const mi = _mIdx(model);
    for(const rule of f.tiers){
      if(rule.m){ if(rule.m.includes(model)) return rule.p; }
      else if(rule.r){ if(mi >= _mIdx(rule.r[0]) && mi <= _mIdx(rule.r[1])) return rule.p; }
      else return rule.p;
    }
    return null;
  }
  return f.p;
}

